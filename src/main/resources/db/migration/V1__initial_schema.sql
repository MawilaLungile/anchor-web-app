-- Anchor schema. Written to run unchanged on PostgreSQL and on H2 (PostgreSQL mode).

CREATE TABLE app_users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  VARCHAR(254)  NOT NULL,
    password_hash          VARCHAR(100)  NOT NULL,
    display_name           VARCHAR(60)   NOT NULL,
    time_zone              VARCHAR(64)   NOT NULL,
    theme                  VARCHAR(10)   NOT NULL DEFAULT 'system',
    default_focus_minutes  INT           NOT NULL DEFAULT 50,
    block_during_focus     BOOLEAN       NOT NULL DEFAULT TRUE,
    cooling_off_minutes    INT           NOT NULL DEFAULT 30,
    streak_start           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    longest_streak_days    INT           NOT NULL DEFAULT 0,
    onboarded              BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX ux_app_users_email ON app_users (email);

CREATE TABLE tasks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    title             VARCHAR(200)  NOT NULL,
    notes             VARCHAR(2000),
    slot              VARCHAR(20)   NOT NULL,
    is_deep           BOOLEAN       NOT NULL DEFAULT TRUE,
    estimate_minutes  INT           NOT NULL DEFAULT 30,
    planned_for       DATE          NOT NULL,
    is_done           BOOLEAN       NOT NULL DEFAULT FALSE,
    completed_at      TIMESTAMP(6) WITH TIME ZONE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_tasks_user_day ON tasks (user_id, planned_for);

CREATE TABLE focus_sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    intention            VARCHAR(200)  NOT NULL,
    task_id              BIGINT,
    planned_minutes      INT           NOT NULL,
    started_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ended_at             TIMESTAMP(6) WITH TIME ZONE,
    status               VARCHAR(20)   NOT NULL,
    break_reason         VARCHAR(300),
    blocks_distractions  BOOLEAN       NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_sessions_user_started ON focus_sessions (user_id, started_at);

CREATE TABLE energy_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT  NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    recorded_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    energy_level  INT     NOT NULL
);
CREATE INDEX ix_energy_user_recorded ON energy_entries (user_id, recorded_at);

CREATE TABLE urge_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    recorded_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    trigger_name  VARCHAR(30)  NOT NULL,
    source        VARCHAR(20)  NOT NULL,
    resisted      BOOLEAN      NOT NULL
);
CREATE INDEX ix_urges_user_recorded ON urge_entries (user_id, recorded_at);

CREATE TABLE blocked_sites (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    domain_name            VARCHAR(253)  NOT NULL,
    list_type              VARCHAR(10)   NOT NULL,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    removal_requested_at   TIMESTAMP(6) WITH TIME ZONE
);
CREATE UNIQUE INDEX ux_sites_user_domain_list ON blocked_sites (user_id, domain_name, list_type);

CREATE TABLE relapses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT  NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    recorded_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    streak_days   INT     NOT NULL
);

CREATE TABLE daily_reviews (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT  NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    review_date      DATE    NOT NULL,
    rating           INT     NOT NULL,
    note             VARCHAR(1000),
    completed_count  INT     NOT NULL DEFAULT 0,
    moved_count      INT     NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_reviews_user_date ON daily_reviews (user_id, review_date);
